/// The registry row for an item id.
pub fn registry(id: i16) -> Option<(bool, &'static str)> {
    let index = REGISTRY.binary_search_by_key(&id, |row| row.0).ok()?;
    Some((REGISTRY[index].1, REGISTRY[index].2))
}
